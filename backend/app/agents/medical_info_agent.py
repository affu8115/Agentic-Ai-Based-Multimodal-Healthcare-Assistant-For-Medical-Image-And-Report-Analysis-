    def process(self, payload: dict) -> dict:
        report_findings = payload.get('report_findings', [])
        image_modality = payload.get('image_modality', '')
        abnormal_values = payload.get('abnormal_values', [])

        explanations = []
        identified_terms = set()

        # Match biomarkers and terms to explain
        for finding in report_findings:
            param_lower = finding.get('parameter', '').lower()
            for key, info in self.GLOSSARY.items():
                if key in param_lower or param_lower in key:
                    if info['term'] not in identified_terms:
                        explanations.append(info)
                        identified_terms.add(info['term'])

        # Check diagnostic keywords
        impressions = payload.get('clinical_impressions', [])
        for imp in impressions:
            kw_lower = imp.get('keyword', '').lower()
            if kw_lower in self.GLOSSARY and self.GLOSSARY[kw_lower]['term'] not in identified_terms:
                explanations.append(self.GLOSSARY[kw_lower])
                identified_terms.add(self.GLOSSARY[kw_lower]['term'])

        # If few terms matched, include general terminology
        if len(explanations) < 2:
            explanations.append(self.GLOSSARY['hemoglobin'])
            explanations.append(self.GLOSSARY['fasting blood glucose'])

        # Formulate patient doctor-consultation questions
        questions = [
            "Are there any specific lifestyle or dietary modifications you recommend based on these findings?",
            "Do any of the parameters marked outside the standard reference range require a repeat confirmatory test?",
            "How do these findings correlate with my current symptoms and physical exam?"
        ]

        if abnormal_values:
            abnormal_names = [a['parameter'] for a in abnormal_values[:2]]
            questions.insert(0, f"What might be contributing to my out-of-range {' and '.join(abnormal_names)} values?")

        if image_modality:
            questions.append(f"Does my {image_modality} suggest a need for any follow-up cross-sectional imaging (such as CT or ultrasound)?")

        plain_summary = (
            "This report summarizes key measurements of your body's biochemical and cellular indicators. "
            "Every individual has a unique baseline, so slight variations from standard laboratory intervals are common. "
            "Always consult your doctor to interpret these values in relation to your overall health and well-being."
        )

        return {
            'plain_language_summary': plain_summary,
            'terminology_explanations': explanations,
            'questions_for_doctor': questions,
            'advice_note': 'Write down these questions and bring a physical or digital copy of this report to your consultation.'
        }
