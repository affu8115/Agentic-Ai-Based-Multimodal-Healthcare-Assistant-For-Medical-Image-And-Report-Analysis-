from .base_agent import BaseAgent
from ..services.ai_service import AIService


class MedicalInfoAgent(BaseAgent):
    """Specialized Agent responsible for translating clinical jargon into accessible layperson explanations and formulating doctor questions."""

    def __init__(self):
        super().__init__(
            name="MedicalInfoAgent",
            description="Explains medical terms, provides patient-friendly summaries, and formulates relevant questions for healthcare provider consultations."
        )

